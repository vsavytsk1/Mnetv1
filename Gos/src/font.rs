/// The five columns of `c`, or `None` if the glyph is not carved.
///
/// Lowercase folds to uppercase -- a deliberate limit, stated rather than
/// silently rendering blanks (Path IV).
pub fn glyph(c: char) -> Option<[u8; 5]> {
    let c = c.to_ascii_uppercase();
    GLYPHS.iter().find(|(g, _)| *g == c).map(|(_, b)| *b)
}

/// Is every character of `s` carved? Useful as a build-time assertion so a
/// label can never silently lose letters.
pub fn covers(s: &str) -> bool {
    s.chars().all(|c| glyph(c).is_some())
}

/// Draw `s` at `(x, y)` (top-left), scaled by `scale`, in `colour`.
/// Returns the advance in pixels.
pub fn text(cv: &mut Canvas, x: i32, y: i32, s: &str, colour: Rgb, scale: i32) -> i32 {
    let mut pen = x;
    for ch in s.chars() {
        if let Some(cols) = glyph(ch) {
            for (cx, col) in cols.iter().enumerate() {
                for row in 0..GH {
                    if col & (1 << row) != 0 {
                        if scale == 1 {
                            cv.set(pen + cx as i32, y + row, colour);
                        } else {
                            cv.fill_rect(
                                pen + cx as i32 * scale,
                                y + row * scale,
                                scale,
                                scale,
                                colour,
                            );
                        }
                    }
                }
            }
        }
        pen += (GW + 1) * scale;
    }
    pen - x
}

/// Pixel width `s` will occupy at `scale`.
pub fn width(s: &str, scale: i32) -> i32 {
    s.chars().count() as i32 * (GW + 1) * scale
}
