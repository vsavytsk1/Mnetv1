//! A 5x7 bitmap font. Pure data plus integer blitting -- no dependency, no
//! `unsafe`, no font file, no shaping engine.
//!
//! Every glyph is five `u8` columns; bit `n` of a column is row `n`, top down.
//! So one character is five bytes and the whole alphabet fits in a few hundred.
//! Chromium reaches a monospace glyph through fontconfig, FreeType, hinting,
//! subpixel positioning and a rasteriser cache. This is the same job in 5 bytes
//! per character, and it is *exactly* reproducible: no AA, no hinting, no
//! platform font stack, so the pixels are bit-identical everywhere.
//!
//! CERTIFIED lane throughout: `u8` data, `i32` coordinates, integer blits.

use crate::palette::Rgb;
use crate::raster::Canvas;

/// Glyph width in pixels, before spacing.
pub const GW: i32 = 5;
/// Glyph height in pixels.
pub const GH: i32 = 7;

